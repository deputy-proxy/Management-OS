<?php

namespace App\Filament\Resources\PayrollExceptions;

use App\Filament\Clusters\General\GeneralCluster;
use App\Filament\Resources\PayrollExceptions\Pages\ListPayrollExceptions;
use App\Filament\Resources\PayrollExceptions\Tables\PayrollExceptionsTable;
use App\Models\PayrollException;
use Filament\Resources\Resource;
use Filament\Schemas\Schema;
use Filament\Tables\Table;
use Hexters\HexaLite\HasHexaLite;
use Illuminate\Auth\Access\Response;
use Illuminate\Database\Eloquent\Model;
use UnitEnum;

class PayrollExceptionResource extends Resource
{
    use HasHexaLite;

    protected static ?string $model = PayrollException::class;

    protected static ?string $recordTitleAttribute = 'code';

    protected static ?int $navigationSort = 10;

    protected static ?string $cluster = GeneralCluster::class;

    protected static string|UnitEnum|null $navigationGroup = 'Human Resources';

    protected static \BackedEnum|string|null $navigationIcon = 'heroicon-o-exclamation-triangle';

    public static function getNavigationBadge(): ?string
    {
        if (! hexa()->can('payroll_exception.index')) {
            return null;
        }

        $count = PayrollException::query()
            ->where('severity', PayrollException::SEVERITY_BLOCKING)
            ->where('status', PayrollException::STATUS_OPEN)
            ->count();

        return $count > 0 ? (string) $count : null;
    }

    public static function getNavigationBadgeColor(): ?string
    {
        return 'danger';
    }

    public static function getNavigationBadgeTooltip(): ?string
    {
        return 'Open blocking payroll exceptions';
    }

    public function defineGates(): array
    {
        return [
            'payroll_exception.index' => __('View payroll validation exceptions'),
            'payroll_exception.resolve' => __('Resolve payroll validation exceptions'),
        ];
    }

    public static function form(Schema $schema): Schema
    {
        return $schema;
    }

    public static function table(Table $table): Table
    {
        return PayrollExceptionsTable::configure($table);
    }

    public static function getPages(): array
    {
        return ['index' => ListPayrollExceptions::route('/')];
    }

    public static function getViewAnyAuthorizationResponse(): Response
    {
        return hexa()->can('payroll_exception.index') ? Response::allow() : Response::deny();
    }

    public static function getCreateAuthorizationResponse(): Response
    {
        return Response::deny('Payroll exceptions are generated by the validation service.');
    }

    public static function getEditAuthorizationResponse(Model $record): Response
    {
        return Response::deny('Payroll exception evidence is immutable. Use the resolution workflow.');
    }

    public static function getDeleteAuthorizationResponse(Model $record): Response
    {
        return Response::deny('Payroll exceptions are retained as audit records.');
    }

    public static function getDeleteAnyAuthorizationResponse(): Response
    {
        return Response::deny('Payroll exceptions are retained as audit records.');
    }
}
